import fs from 'node:fs';

const MDN_SELECTORS_PATH = 'node_modules/mdn-data/css/selectors.json';
const WEBREF_CSS_PATH = 'node_modules/@webref/css/css.json';
const OUTPUT_PATH = 'src/data/gen/selectors.ts';

function main() {
    const selectors = JSON.parse(fs.readFileSync(MDN_SELECTORS_PATH, 'utf8'));
    
    const pseudoClasses = new Set<string>();
    const pseudoElements = new Set<string>();
    const knownPseudoElements = new Set<string>();
    const knownFunctionalPseudoElements = new Set<string>();

    for (const [name] of Object.entries(selectors)) {
        if (name.startsWith('::')) {
            const raw = name.substring(2);
            if (raw.endsWith('()')) {
                const clean = raw.slice(0, -2).toLowerCase();
                pseudoElements.add(clean);
                knownFunctionalPseudoElements.add(clean);
            } else {
                const clean = raw.toLowerCase();
                pseudoElements.add(clean);
                if (!clean.startsWith('-')) {
                    knownPseudoElements.add(clean);
                }
            }
        } else if (name.startsWith(':')) {
            pseudoClasses.add(name.substring(1).replace('()', '').toLowerCase());
        }
    }

    if (fs.existsSync(WEBREF_CSS_PATH)) {
        const webref = JSON.parse(fs.readFileSync(WEBREF_CSS_PATH, 'utf8')) as {
            selectors?: Array<{ name: string }>;
        };
        for (const sel of webref.selectors || []) {
            const name = sel.name;
            if (name.startsWith('::')) {
                const raw = name.substring(2);
                if (raw.endsWith('()')) {
                    const clean = raw.slice(0, -2).toLowerCase();
                    pseudoElements.add(clean);
                    knownFunctionalPseudoElements.add(clean);
                } else {
                    const clean = raw.toLowerCase();
                    pseudoElements.add(clean);
                    if (!clean.startsWith('-')) {
                        knownPseudoElements.add(clean);
                    }
                }
            } else if (name.startsWith(':')) {
                pseudoClasses.add(name.substring(1).replace('()', '').toLowerCase());
            }
        }
    }

    let tsContent = `/**
 * @license
 * Copyright 2026 Google LLC
 *
 * Licensed under the Apache License, Version 2.0 (the "License");
 * you may not use this file except in compliance with the License.
 * You may obtain a copy of the License at
 *
 *     https://www.apache.org/licenses/LICENSE-2.0
 *
 * Unless required by applicable law or agreed to in writing, software
 * distributed under the License is distributed on an "AS IS" BASIS,
 * WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
 * See the License for the specific language governing permissions and
 * limitations under the License.
 */\n\n// @generated by scripts/codegen/generate_selectors.ts. Do not edit.\n// Machine-generated.\n\n`;
    
    tsContent += `export const PSEUDO_CLASSES: Set<string> = /* @__PURE__ */ new Set('${Array.from(pseudoClasses).sort().join(',')}'.split(','));\n\n`;
    tsContent += `export const PSEUDO_ELEMENTS: Set<string> = /* @__PURE__ */ new Set('${Array.from(pseudoElements).sort().join(',')}'.split(','));\n\n`;

    tsContent += `/**\n * Known standard non-functional pseudo-elements recognized by the cascade.\n * selectors-4 § 3.7 #pseudo-elements\n */\n`;
    tsContent += `export const KNOWN_PSEUDO_ELEMENTS: ReadonlySet<string> = /* @__PURE__ */ new Set('${Array.from(knownPseudoElements).sort().join(',')}'.split(','));\n\n`;

    tsContent += `/**\n * Known standard functional pseudo-elements recognized by the cascade.\n * selectors-4 § 3.7 #pseudo-elements\n */\n`;
    tsContent += `export const KNOWN_FUNCTIONAL_PSEUDO_ELEMENTS: ReadonlySet<string> = /* @__PURE__ */ new Set('${Array.from(knownFunctionalPseudoElements).sort().join(',')}'.split(','));\n`;


    fs.writeFileSync(OUTPUT_PATH, tsContent);
    console.log(`Generated ${OUTPUT_PATH}`);
}

main();
