/**
 * Resolves a logical property to its physical counterpart based on writing mode and direction.
 */
export function resolveLogicalProperty(name: string, writingMode: string = 'horizontal-tb', direction: string = 'ltr'): string {
  if (!(name in LOGICAL_MAPPING)) {
    return name;
  }

  let blockStart = 'top';
  let blockEnd = 'bottom';
  let inlineStart = 'left';
  let inlineEnd = 'right';
  let blockAxis = 'y';
  let inlineAxis = 'x';

  if (writingMode === 'vertical-rl') {
    blockStart = 'right';
    blockEnd = 'left';
    inlineStart = 'top';
    inlineEnd = 'bottom';
    blockAxis = 'x';
    inlineAxis = 'y';
  } else if (writingMode === 'vertical-lr') {
    blockStart = 'left';
    blockEnd = 'right';
    inlineStart = 'top';
    inlineEnd = 'bottom';
    blockAxis = 'x';
    inlineAxis = 'y';
  }

  if (direction === 'rtl') {
    const tmp = inlineStart;
    inlineStart = inlineEnd;
    inlineEnd = tmp;
  }

  if (name.startsWith('inset-block-start')) return blockStart;
  if (name.startsWith('inset-block-end')) return blockEnd;
  if (name.startsWith('inset-inline-start')) return inlineStart;
  if (name.startsWith('inset-inline-end')) return inlineEnd;

    const radius = (s1: string, s2: string) => {
      const v = (s1 === 'top' || s1 === 'bottom') ? s1 : s2;
      const h = (s1 === 'left' || s1 === 'right') ? s1 : s2;
      return `-${v}-${h}-radius`;
    };
    const shape = (s1: string, s2: string) => {
      const v = (s1 === 'top' || s1 === 'bottom') ? s1 : s2;
      const h = (s1 === 'left' || s1 === 'right') ? s1 : s2;
      return `-${v}-${h}-shape`;
    };

    const replacements = [
      { logical: '-block-start', physical: `-${blockStart}` },
      { logical: '-block-end', physical: `-${blockEnd}` },
      { logical: '-inline-start', physical: `-${inlineStart}` },
      { logical: '-inline-end', physical: `-${inlineEnd}` },
      { logical: '-start-start-radius', physical: radius(blockStart, inlineStart) },
      { logical: '-start-end-radius', physical: radius(blockStart, inlineEnd) },
      { logical: '-end-start-radius', physical: radius(blockEnd, inlineStart) },
      { logical: '-end-end-radius', physical: radius(blockEnd, inlineEnd) },
      { logical: '-start-start-shape', physical: shape(blockStart, inlineStart) },
      { logical: '-start-end-shape', physical: shape(blockStart, inlineEnd) },
      { logical: '-end-start-shape', physical: shape(blockEnd, inlineStart) },
      { logical: '-end-end-shape', physical: shape(blockEnd, inlineEnd) },
      { logical: '-block', physical: `-${blockAxis}` },
      { logical: '-inline', physical: `-${inlineAxis}` },
    ];

  let resolved = name;
  for (const { logical, physical } of replacements) {
    if (resolved.includes(logical)) {
      resolved = resolved.replace(logical, physical);
      break;
    }
  }

  if (resolved === 'block-size') return writingMode.startsWith('vertical') ? 'width' : 'height';
  if (resolved === 'inline-size') return writingMode.startsWith('vertical') ? 'height' : 'width';
  if (resolved === 'min-block-size') return writingMode.startsWith('vertical') ? 'min-width' : 'min-height';
  if (resolved === 'min-inline-size') return writingMode.startsWith('vertical') ? 'min-height' : 'min-width';
  if (resolved === 'max-block-size') return writingMode.startsWith('vertical') ? 'max-width' : 'max-height';
  if (resolved === 'max-inline-size') return writingMode.startsWith('vertical') ? 'max-height' : 'max-width';
  if (resolved === 'contain-intrinsic-block-size') return writingMode.startsWith('vertical') ? 'contain-intrinsic-width' : 'contain-intrinsic-height';
  if (resolved === 'contain-intrinsic-inline-size') return writingMode.startsWith('vertical') ? 'contain-intrinsic-height' : 'contain-intrinsic-width';

  return resolved;
}

export function resolvePhysicalProperty(name: string, writingMode: string = 'horizontal-tb', direction: string = 'ltr'): string {
  for (const logical in LOGICAL_MAPPING) {
    const resolved = resolveLogicalProperty(logical, writingMode, direction);
    if (resolved === name) {
      return logical;
    }
  }
  return name;
}

export function getPhysicalToLogicalMapping(physicals: readonly string[], writingMode: string = 'horizontal-tb', direction: string = 'ltr'): Record<string, string> {
  const mapping: Record<string, string> = {};
  for (const ph of physicals) {
    mapping[ph] = resolvePhysicalProperty(ph, writingMode, direction);
  }
  return mapping;
}
